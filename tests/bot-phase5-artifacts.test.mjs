test('audio never becomes a path, a URL or a log line', async () => {
  const voice = await read('packages/host-protocol/src/voice-rpc.ts')
  assert.doesNotMatch(voice, /path:|url:|mimeType/)
  const storage = await read('packages/host-core/src/voice/uploads.ts')
  // Every filename is generated by the Host and checked against that shape.
  assert.match(storage, /GENERATED_ID/)
  const service = await read('packages/host-core/src/voice/service.ts')
  assert.doesNotMatch(service, /console\.(log|info|warn|error)/)
  // Only the confirmed text reaches the engine; the recording is not an attachment.
  assert.match(service, /attachments: \[\]/)
  const worker = await read('apps/host/src/asr-worker.ts')
  assert.doesNotMatch(worker, /console\.(log|info|warn|error)/)
})

test('the application asks for the microphone on a gesture, and for nothing else', async () => {
  const permissions = await read('apps/bot-desktop/src/main/microphone-permissions.ts')
  // Both handlers, or the synchronous check answers its default.
  assert.match(permissions, /setPermissionRequestHandler/)
  assert.match(permissions, /setPermissionCheckHandler/)
  assert.match(permissions, /armed/)
  const index = await read('apps/bot-desktop/src/main/index.ts')
  assert.match(index, /installMicrophonePermissions/)
  // The old blanket refusal is gone, but nothing grants "media" wholesale either.
  assert.doesNotMatch(index, /setPermissionRequestHandler\(\(_contents, _permission, callback\) => callback\(false\)\)/)
  const builder = await read('apps/bot-desktop/electron-builder.yml')
  assert.match(builder, /NSMicrophoneUsageDescription/)
  assert.match(builder, /entitlements: build\/entitlements\.mac\.plist/)
  const entitlements = await read('apps/bot-desktop/build/entitlements.mac.plist')
  assert.match(entitlements, /com\.apple\.security\.device\.audio-input/)
  // The camera is deliberately absent, and nothing disables the sandbox or Gatekeeper.
  assert.doesNotMatch(entitlements, /device\.camera/)
  assert.doesNotMatch(entitlements, /app-sandbox/)
})

