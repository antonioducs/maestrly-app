test('the reported service version matches the package that is built and shipped', async () => {
  // These two drifted apart before: `host.inspect` said one thing and the package manifest another,
  // and the rollout kit compares exactly these to refuse a downgrade. A mismatch would let an
  // operator install something older than what is running.
  const declared = JSON.parse(await read('apps/host/package.json')).version
  const reported = /serviceVersion: '([^']+)'/.exec(await read('packages/host-core/src/service.ts'))?.[1]
  assert.equal(reported, declared)
})

test('the phase is wired into the repository checks', async () => {
  const manifest = JSON.parse(await read('package.json'))
  for (const script of ['check:bot-phase5', 'test:bot-phase5', 'test:e2e:bot-phase5', 'build:host:asr', 'lab:bot:phase5'])
    assert.ok(manifest.scripts[script], `missing script ${script}`)
  // The aggregate check and test include the new phase.
  assert.match(manifest.scripts.check, /check:bot-phase5/)
  assert.match(manifest.scripts.test, /test:bot-phase5/)
  // The laboratory is never part of an automated run.
  assert.doesNotMatch(manifest.scripts.test, /lab:bot:phase5/)
  assert.doesNotMatch(manifest.scripts['test:bot-phase5'], /lab:|ssh/)
})
